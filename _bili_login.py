# -*- coding: utf-8 -*-
"""B站扫码登录：打开页面，用户自己扫码，检测到 SESSDATA 自动保存。

B站真登录判据：SESSDATA（+ bili_jct）。其余 cookie 匿名访客也有，不能作为判据。
"""
import json
import time
from pathlib import Path

from playwright.sync_api import sync_playwright

PROFILE = r"C:\Users\xianw\.video-research\profiles\bilibili"
COOKIE_DIR = Path.home() / ".video-research" / "cookies"
COOKIE_DIR.mkdir(parents=True, exist_ok=True)

LOGIN_KEYS = {"SESSDATA", "bili_jct", "DedeUserID"}


def log(m: str) -> None:
    print(f"[{time.strftime('%H:%M:%S')}] {m}", flush=True)


def save(cookies: list[dict]) -> int:
    wanted = [c for c in cookies if "bilibili.com" in (c.get("domain") or "")]

    # B站 SESSDATA 内嵌真实过期时间（形如 "hash,1809225649,xxx"），
    # 而浏览器给的 cookie expires 只有 7 天。服务端认的是内嵌时间戳（约 180 天）。
    # 若不修正，7 天后 Python 的 CookieJar 会自己丢弃仍然有效的凭证。
    def fix_expiry(c: dict) -> dict:
        c = dict(c)
        if c.get("name") in ("SESSDATA", "bili_jct", "DedeUserID", "DedeUserID__ckMd5"):
            try:
                import urllib.parse
                dec = urllib.parse.unquote(c.get("value", ""))
                parts = dec.split(",")
                if len(parts) >= 2 and parts[1].isdigit():
                    real_exp = int(parts[1])
                    if real_exp > int(c.get("expires") or 0):
                        c["_browser_expires"] = c.get("expires")
                        c["expires"] = real_exp
            except Exception:
                pass
        return c

    wanted = [fix_expiry(c) for c in wanted]

    (COOKIE_DIR / "bili.json").write_text(
        json.dumps(wanted, ensure_ascii=False, indent=2), encoding="utf-8")

    lines = ["# Netscape HTTP Cookie File", "# generated by vsearch", ""]
    for c in wanted:
        dom = c.get("domain", "")
        exp = int(c.get("expires") or 0) or int(time.time()) + 86400 * 365
        lines.append("\t".join([
            dom, "TRUE" if dom.startswith(".") else "FALSE",
            c.get("path", "/"), "TRUE" if c.get("secure") else "FALSE",
            str(exp), c.get("name", ""), c.get("value", "")]))
    (COOKIE_DIR / "bili.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # 顺带写 polylens MCP 的 cookie 格式
    try:
        cache = Path.home() / ".cache" / "polylens-bilibili"
        cache.mkdir(parents=True, exist_ok=True)
        pairs = [f"{c['name']}={c['value']}" for c in wanted if c.get("name")]
        (cache / "cookie").write_text("; ".join(pairs), encoding="utf-8")
    except Exception:
        pass

    return len(wanted)


def main() -> int:
    with sync_playwright() as p:
        ctx = p.chromium.launch_persistent_context(
            PROFILE, channel="msedge", headless=False, locale="zh-CN",
            viewport={"width": 1180, "height": 800},
            args=["--disable-blink-features=AutomationControlled",
                  "--no-first-run", "--no-default-browser-check"],
        )
        pg = ctx.pages[0] if ctx.pages else ctx.new_page()

        names = {c["name"] for c in ctx.cookies()}
        if names & LOGIN_KEYS:
            log(f"✓ 已是登录态（{', '.join(sorted(names & LOGIN_KEYS))}），无需扫码")
            save(ctx.cookies())
            ctx.close()
            return 0

        log("打开 B站登录页…")
        try:
            pg.goto("https://passport.bilibili.com/login",
                    wait_until="domcontentloaded", timeout=60000)
        except Exception as e:
            log(f"goto 告警（继续）: {type(e).__name__}")
        pg.wait_for_timeout(3000)
        log(f"页面标题: {pg.title()}")

        log("=" * 58)
        log("浏览器已打开 —— 请用 B站 App 扫码登录，我在这边等。")
        log("检测到 SESSDATA 会自动保存并关闭。")
        log("=" * 58)

        deadline = time.time() + 600
        while time.time() < deadline:
            time.sleep(2)
            try:
                cookies = ctx.cookies()
            except Exception:
                log("浏览器已关闭")
                break
            hit = {c["name"] for c in cookies} & LOGIN_KEYS
            if hit:
                n = save(cookies)
                log(f"✓ 登录成功！{', '.join(sorted(hit))}，已存 {n} 条 cookie")
                ctx.close()
                return 0
            left = int(deadline - time.time())
            if left % 60 < 2:
                log(f"等待中… 剩余 {left}s")

        log("✗ 超时（10 分钟）")
        try:
            ctx.close()
        except Exception:
            pass
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
